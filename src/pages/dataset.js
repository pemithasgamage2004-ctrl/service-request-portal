import { el, pageHeader } from '../lib/dom.js';
import { loadSample, countBy, SAMPLE_CSV_URL, SAMPLE_JSON_URL, HISTORY_CSV_URL } from '../lib/data.js';
import { DEPARTMENTS, REQUEST_TYPES, PRIORITIES, STATUSES, SLA_DAYS } from '../lib/enums.js';
import { REQUEST_FIELDS, HISTORY_FIELDS } from '../content/fieldDictionary.js';

const PREVIEW_ROWS = 15;

function dictTable(fields) {
  return el('div', { class: 'table-wrap' },
    el('table', {},
      el('thead', {}, el('tr', {}, ['Field', 'Type', 'Description', 'Allowed values / rules'].map((h) => el('th', { text: h })))),
      el('tbody', {}, fields.map((f) =>
        el('tr', {}, el('td', {}, el('code', { text: f.name })), el('td', { text: f.type }), el('td', { text: f.description }), el('td', { text: f.allowed })),
      )),
    ),
  );
}

function distributionTable(title, counts, total) {
  return el('div', { class: 'card' },
    el('h3', { text: title }),
    el('table', {},
      el('tbody', {}, Object.entries(counts).map(([k, v]) =>
        el('tr', {}, el('td', { text: k }), el('td', { text: String(v) }), el('td', { class: 'muted', text: `${Math.round((v / total) * 100)}%` })),
      )),
    ),
  );
}

function previewTable(rows, showAll) {
  const cols = ['id', 'created_at', 'department', 'request_type', 'priority', 'status', 'title', 'requester_name'];
  const shown = showAll ? rows : rows.slice(0, PREVIEW_ROWS);
  return el('div', { class: 'table-wrap' },
    el('table', {},
      el('thead', {}, el('tr', {}, cols.map((c) => el('th', { text: c })))),
      el('tbody', {}, shown.map((r) =>
        el('tr', {}, cols.map((c) => el('td', { text: c === 'created_at' ? r[c].slice(0, 10) : r[c] }))),
      )),
    ),
  );
}

function downloadLink(href, label, filename) {
  return el('a', { class: 'btn', href, text: label, attrs: { download: filename } });
}

export default function render(root) {
  root.append(pageHeader('Sample Dataset', 'A seeded, reproducible dataset of fictional service requests used by the Dashboard and Workflow pages.'));
  const body = el('div', {}, el('p', { class: 'muted', text: 'Loading dataset…' }));
  root.append(body);

  loadSample()
    .then(({ meta, requests }) => {
      body.replaceChildren();
      const total = requests.length;
      const cfg = meta.config;
      const historyCount = requests.reduce((s, r) => s + r.history.length, 0);

      // Summary + downloads
      body.append(
        el('div', { class: 'grid grid-4' },
          stat('Requests', total),
          stat('Status changes', historyCount),
          stat('Submitted between', `${meta.created_range[0]} → ${meta.created_range[1]}`),
          stat('Seed / as-of', `${meta.seed} / ${meta.as_of.slice(0, 10)}`),
        ),
        el('div', { class: 'card' },
          el('h2', { text: 'Download' }),
          el('div', { class: 'btn-row' },
            downloadLink(SAMPLE_CSV_URL, 'requests.csv', 'requests.csv'),
            downloadLink(SAMPLE_JSON_URL, 'requests.json', 'requests.json'),
            downloadLink(HISTORY_CSV_URL, 'status_history.csv', 'status_history.csv'),
          ),
          el('p', { class: 'small muted' },
            'JSON contains each request with its nested status history. The CSV is split into two flat files that mirror the SQL tables ',
            el('code', { text: 'requests' }), ' and ', el('code', { text: 'request_status_history' }),
            '. CSV cells beginning with = + - @ are prefixed with an apostrophe to prevent spreadsheet formula injection. ',
            'These files are the original sample; requests you add on the Workflow page are stored only in your browser.'),
        ),
      );

      // How it was generated
      body.append(
        el('div', { class: 'card' },
          el('h2', { text: 'How the data was generated' }),
          el('p', {}, 'Generated by ', el('code', { text: 'scripts/generate-data.mjs' }), ' (Node.js, no dependencies) using a seeded mulberry32 pseudo-random generator. ',
            'The same seed always produces byte-identical files; the CI pipeline regenerates the data and fails if it differs from the committed files.'),
          el('ul', {},
            el('li', { text: `Seed ${meta.seed}; ${total} requests submitted between ${meta.created_range[0]} and ${meta.created_range[1]} (UTC, business hours 08:00–17:30).` }),
            el('li', { text: 'Submission dates: weekdays weighted ~7x more than weekends, with volume trending upward over the period.' }),
            el('li', { text: `Weighted draws (relative weights): department (${fmtWeights(cfg.weights.department)}); type (${fmtWeights(cfg.weights.request_type)}); priority (${fmtWeights(cfg.weights.priority)}).` }),
            el('li', { text: `Each request is walked through the workflow with randomised step durations per priority (review pickup, decision, fulfilment). ${pct(cfg.APPROVAL_PROBABILITY)} of decisions are approvals. ${pct(cfg.STALL_PROBABILITY)} of steps "stall" (${cfg.STALL_FACTOR}x longer) to create realistic SLA breaches.` }),
            el('li', { text: `Backlog: ${pct(cfg.BACKLOG_PROBABILITY)} of requests from the last ${cfg.BACKLOG_WINDOW_DAYS} days stop at a random open stage (Submitted / Under Review / Approved), so there is a realistic open queue.` }),
            el('li', { text: `No event happens after the simulation time ${meta.as_of}. Due date = submission + SLA (${Object.entries(SLA_DAYS).map(([p, d]) => `${p} ${d}d`).join(', ')}).` }),
            el('li', { text: 'Names are random combinations of first/last names from a fixed list; employee IDs are synthetic. No real personal data is used.' }),
          ),
          el('p', { class: 'small muted' }, 'Regenerate with ', el('code', { text: 'node scripts/generate-data.mjs' }), '.'),
        ),
        el('h2', { text: 'Distribution of the generated data' }),
        el('div', { class: 'grid grid-4' },
          distributionTable('Status', countBy(requests, 'status', STATUSES), total),
          distributionTable('Priority', countBy(requests, 'priority', PRIORITIES), total),
          distributionTable('Department', countBy(requests, 'department', DEPARTMENTS), total),
          distributionTable('Request type', countBy(requests, 'request_type', REQUEST_TYPES), total),
        ),
      );

      // Field dictionary
      body.append(
        el('h2', { text: 'Field dictionary' }),
        el('h3', { text: 'requests' }),
        dictTable(REQUEST_FIELDS),
        el('h3', { text: 'status history (nested "history" in JSON / status_history.csv)' }),
        dictTable(HISTORY_FIELDS),
      );

      // Preview
      const previewHolder = el('div', {}, previewTable(requests, false));
      const toggle = el('button', { class: 'btn btn-secondary btn-sm', type: 'button', text: `Show all ${total} rows` });
      let all = false;
      toggle.addEventListener('click', () => {
        all = !all;
        previewHolder.replaceChildren(previewTable(requests, all));
        toggle.textContent = all ? `Show first ${PREVIEW_ROWS} rows` : `Show all ${total} rows`;
      });
      body.append(el('h2', { text: 'Preview' }), previewHolder, el('div', { class: 'btn-row preview-toggle' }, toggle));
    })
    .catch((err) => {
      body.replaceChildren(el('div', { class: 'alert alert-error', text: err.message }));
    });
}

const pct = (x) => `${Math.round(x * 100)}%`;
const fmtWeights = (w) => Object.entries(w).map(([k, v]) => `${k} ${v}`).join(', ');

function stat(label, value) {
  return el('div', { class: 'card stat' }, el('div', { class: 'stat-label', text: label }), el('div', { class: 'stat-value', text: String(value) }));
}
